"""Writes learned weights (4 inputs) into the firmware header and training/weights.json.
Usage: python3 export.py learned.txt"""
import sys, json, os, numpy as np
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
w = np.loadtxt(sys.argv[1]); i = 0
def take(n, shape=None):
    global i; a = w[i:i+n]; i += n; return a.reshape(shape) if shape else a
W1 = take(28, (7, 4)); b1 = take(7); W2 = take(49, (7, 7)); b2 = take(7); W3 = take(14, (2, 7)); b3 = take(2)
assert i == len(w), "expected 107 weights for a 4-7-7-2 network"
f = lambda x: f"{x: .6f}f"
with open(os.path.join(ROOT, "firmware", "linefollower", "weights.h"), "w") as h:
    h.write("// Generated by learn/export.py from weights learned in the simulator (learn/learn.cpp). Do not edit by hand.\n")
    h.write("#pragma once\n\n#define NN_IN 4\n#define NN_H1 7\n#define NN_H2 7\n#define NN_OUT 2\n\n")
    for k, (W, b) in enumerate(((W1, b1), (W2, b2), (W3, b3)), 1):
        rows = ",\n".join("  {" + ", ".join(f(x) for x in r) + "}" for r in W)
        h.write(f"static const float NN_W{k}[{W.shape[0]}][{W.shape[1]}] = {{\n{rows}\n}};\n")
        h.write(f"static const float NN_B{k}[{len(b)}] = {{" + ", ".join(f(x) for x in b) + "};\n\n")
json.dump({"sizes": [4, 7, 7, 2], "W": [W1.tolist(), W2.tolist(), W3.tolist()], "b": [b1.tolist(), b2.tolist(), b3.tolist()],
           "source": "learn/learn.cpp (evolution strategy in the simulator)"}, open(os.path.join(ROOT, "training", "weights.json"), "w"))
print("wrote firmware/linefollower/weights.h and training/weights.json")
