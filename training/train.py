#!/usr/bin/env python3
"""Train the line follower network and export it for the ESP32.

Network: 4 IR sensors -> 7 tanh -> 7 tanh -> 2 sigmoid (left motor, right motor).
Only numpy is needed.

Usage:
  python3 train.py                       # train on the built-in 16-pattern table
  python3 train.py --csv my_drive.csv    # train on data logged from the real car
  python3 train.py --out ../firmware/linefollower/weights.h

CSV format (one header line, then one row per sample, speeds between 0 and 1):
  s1,s2,s3,s4,left,right
  0,1,1,0,0.80,0.80
"""
import argparse
import csv
import json

import numpy as np

SIZES = (4, 7, 7, 2)


def teacher(bits):
    """Hand-written rule that labels the built-in table.

    The line position is the average of the sensors that see it (-1.5 to +1.5,
    negative means the line is on the left). The car slows the wheel on the side
    where the line is. With no line under any sensor the car drives straight.
    """
    on = [i - 1.5 for i, b in enumerate(bits) if b]
    if not on:
        return [0.65, 0.65]
    e = sum(on) / len(on)
    base = 0.8 - 0.12 * abs(e)
    g = 0.30
    clamp = lambda x: min(1.0, max(0.0, x))
    return [clamp(base + g * e), clamp(base - g * e)]


def builtin_table():
    X, Y = [], []
    for p in range(16):
        bits = [(p >> 3) & 1, (p >> 2) & 1, (p >> 1) & 1, p & 1]
        X.append(bits)
        Y.append(teacher(bits))
    return np.array(X, dtype=float), np.array(Y, dtype=float)


def load_csv(path):
    X, Y = [], []
    with open(path, newline="") as f:
        for row in csv.DictReader(f):
            X.append([float(row[k]) for k in ("s1", "s2", "s3", "s4")])
            Y.append([float(row["left"]), float(row["right"])])
    if not X:
        raise SystemExit("The CSV file has no rows.")
    return np.array(X), np.array(Y)


class Net:
    def __init__(self, seed=1):
        rng = np.random.default_rng(seed)
        self.W, self.b = [], []
        for ni, no in zip(SIZES[:-1], SIZES[1:]):
            lim = np.sqrt(6.0 / (ni + no))
            self.W.append(rng.uniform(-lim, lim, size=(no, ni)))  # W[out][in], same layout as the C code
            self.b.append(np.zeros(no))

    def forward(self, X):
        acts = [X]
        last = len(self.W) - 1
        for l, (W, b) in enumerate(zip(self.W, self.b)):
            z = acts[-1] @ W.T + b
            acts.append(1.0 / (1.0 + np.exp(-z)) if l == last else np.tanh(z))
        return acts

    def train(self, X, Y, epochs=2400, lr=0.02, log_every=400):
        R = len(X)
        m = [np.zeros_like(p) for p in self.W + self.b]
        v = [np.zeros_like(p) for p in self.W + self.b]
        b1, b2, eps = 0.9, 0.999, 1e-8
        loss = 0.0
        for t in range(1, epochs + 1):
            acts = self.forward(X)
            err = acts[-1] - Y
            loss = float(np.mean(err ** 2))
            d = 2 * err * acts[-1] * (1 - acts[-1]) / R
            gW, gb = [None] * len(self.W), [None] * len(self.W)
            for l in range(len(self.W) - 1, -1, -1):
                gW[l] = d.T @ acts[l]
                gb[l] = d.sum(axis=0)
                if l > 0:
                    d = (d @ self.W[l]) * (1 - acts[l] ** 2)
            params, grads = self.W + self.b, gW + gb
            for i, (p, g) in enumerate(zip(params, grads)):
                m[i] = b1 * m[i] + (1 - b1) * g
                v[i] = b2 * v[i] + (1 - b2) * g * g
                p -= lr * (m[i] / (1 - b1 ** t)) / (np.sqrt(v[i] / (1 - b2 ** t)) + eps)
            if log_every and (t % log_every == 0 or t == 1):
                print(f"step {t:5d}  error {loss:.2e}")
        return loss


def fmt(x):
    return f"{x: .6f}f"


def c_matrix(W):
    return ",\n".join("  {" + ", ".join(fmt(x) for x in row) + "}" for row in W)


def write_header(net, path):
    with open(path, "w") as f:
        f.write("// Generated by training/train.py. Do not edit by hand.\n")
        f.write("#pragma once\n\n")
        f.write(f"#define NN_IN {SIZES[0]}\n#define NN_H1 {SIZES[1]}\n#define NN_H2 {SIZES[2]}\n#define NN_OUT {SIZES[3]}\n\n")
        for i, name in enumerate(("NN_W1", "NN_W2", "NN_W3")):  # NN_ prefix: Arduino already defines B1, B2 ... as binary constants
            no, ni = net.W[i].shape
            f.write(f"static const float {name}[{no}][{ni}] = {{\n{c_matrix(net.W[i])}\n}};\n")
            f.write(f"static const float NN_B{i + 1}[{no}] = {{" + ", ".join(fmt(x) for x in net.b[i]) + "};\n\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv", help="logged driving data (s1,s2,s3,s4,left,right)")
    ap.add_argument("--epochs", type=int, default=2400)
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--out", default="weights.h", help="C header to write")
    ap.add_argument("--json", default="weights.json", help="same weights as JSON, for checking")
    args = ap.parse_args()

    X, Y = load_csv(args.csv) if args.csv else builtin_table()
    print(f"{len(X)} training rows")
    net = Net(args.seed)
    final = net.train(X, Y, epochs=args.epochs)
    n_params = sum(w.size + b.size for w, b in zip(net.W, net.b))
    print(f"final error {final:.2e}, {n_params} weights ({n_params * 4} bytes as float32)")

    if not args.csv:
        out = net.forward(X)[-1]
        print("worst motor-speed difference from the table:", float(np.abs(out - Y).max()))
        print("pattern   left  right")
        for row, o in zip(X, out):
            print("".join(str(int(b)) for b in row), f"  {o[0]:.2f}  {o[1]:.2f}")

    write_header(net, args.out)
    with open(args.json, "w") as f:
        json.dump({"sizes": SIZES, "W": [w.tolist() for w in net.W], "b": [b.tolist() for b in net.b]}, f)
    print(f"wrote {args.out} and {args.json}")


if __name__ == "__main__":
    main()
